// 检查某游戏是否已引导过
function checkGuided(gameId) {
  const guided = wx.getStorageSync('guided_games') || []
  return guided.includes(gameId)
}

// 标记某游戏已引导
function markGuided(gameId) {
  const guided = wx.getStorageSync('guided_games') || []
  if (!guided.includes(gameId)) {
    guided.push(gameId)
    wx.setStorageSync('guided_games', guided)
  }
}

